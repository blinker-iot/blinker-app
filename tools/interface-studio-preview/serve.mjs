import { startFixtureGateway } from './gateway.mjs';
import { mkdtempSync, symlinkSync, readFileSync, writeFileSync, cpSync, mkdirSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const temp = realpathSync(mkdtempSync(resolve(tmpdir(), 'blinker-studio-qa-')));
for (const name of ['public', 'node_modules', 'device-template']) symlinkSync(resolve(root, name), resolve(temp, name));
cpSync(resolve(root, 'src'), resolve(temp, 'src'), { recursive: true });
mkdirSync(resolve(temp, 'tools'), { recursive: true });
cpSync(resolve(root, 'tools/interface-studio-preview'), resolve(temp, 'tools/interface-studio-preview'), { recursive: true });
const config = JSON.parse(readFileSync(resolve(root, 'angular.json'), 'utf8'));
const build = config.projects.app.architect.build;
build.options.browser = 'tools/interface-studio-preview/main.ts';
build.options.tsConfig = 'tsconfig.preview.json';
build.options.preserveSymlinks = false;
build.options.outputPath = { base: resolve(temp, 'output'), browser: '' };
writeFileSync(resolve(temp, 'angular.json'), JSON.stringify(config));
writeFileSync(resolve(temp, 'tsconfig.json'), readFileSync(resolve(root, 'tsconfig.json')));
writeFileSync(resolve(temp, 'tsconfig.preview.json'), JSON.stringify({ extends: './tsconfig.json', compilerOptions: { baseUrl: temp }, files: ['tools/interface-studio-preview/main.ts', 'src/polyfills.ts'], include: ['src/**/*.d.ts'] }));
const port = process.env.STUDIO_QA_PORT || '4301';
const gateway = await startFixtureGateway(root);
writeFileSync(resolve(temp, 'proxy.json'), JSON.stringify({ '/studio-api/**': { target: `http://127.0.0.1:${gateway.address().port}`, secure: false } }));
console.log(`Visual QA fixture: http://127.0.0.1:${port}/device-manager/studio-fixture/uic`);
const child = spawn(process.execPath, [resolve(root, 'node_modules/@angular/cli/bin/ng.js'), 'serve', '--host', '127.0.0.1', '--port', port, '--proxy-config', 'proxy.json', '--configuration', 'development'], { cwd: temp, stdio: 'inherit' });
process.on('SIGINT', () => child.kill('SIGINT'));
process.on('SIGTERM', () => child.kill('SIGTERM'));
child.on('exit', code => { gateway.close(); process.exit(code || 0); });
